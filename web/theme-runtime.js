/* One data-only renderer shared by main window, workshop preview and capture. */
"use strict";
const ThemeRuntime = (() => {
  const root = document.documentElement;
  const textTargets = {
    name: ".haruka-name > span", signature: ".haruka-name em", heading: ".haruka-intro h1",
    subtitle: ".haruka-description", eyebrow: ".haruka-eyebrow", motto: ".haruka-name small",
    vertical: ".haruka-vertical", sceneNumber: ".haruka-scene-number .scene-index",
    sceneTitle: ".haruka-scene-number .scene-title", sectionNumber: ".haruka-section-no"
  };
  const defaultFonts = {
    name: '"STXingkai", "华文行楷", "KaiTi", cursive',
    signature: '"Freestyle Script", "Lucida Handwriting", cursive',
    heading: '"STZhongsong", "SimSun", serif',
    subtitle: 'var(--font)', eyebrow: 'var(--font)', motto: 'var(--font)',
    vertical: 'var(--font)', sceneNumber: 'Georgia, serif', sceneTitle: 'var(--font)', sectionNumber: 'Georgia, serif'
  };
  function fontFamily(name, fallback) {
    if (typeof name !== 'string' || !name || name.length > 100 || /[\x00-\x1f\x7f]/.test(name)) return fallback;
    // Quote as one literal font family, never interpret user text as a CSS list/rule.
    return '"' + name.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '", ' + fallback;
  }
  let original = null;
  const vars = [];
  function set(name, value) { root.style.setProperty(name, value); if (!vars.includes(name)) vars.push(name); }
  function reset() {
    vars.splice(0).forEach(name => root.style.removeProperty(name));
    delete root.dataset.customTheme; delete root.dataset.characterSide;
    delete document.body.dataset.themeCompact;
    if (original) {
      for (const [key, selector] of Object.entries(textTargets)) {
        const element = document.querySelector(selector);
        if (element) element.innerHTML = original[key]; // cached trusted built-in markup only
      }
      const img = document.querySelector(".haruka-oc"); if (img) img.src = original.image;
    }
  }
  function apply(payload, capture = false) {
    reset();
    const c = payload.config, assets = payload.assets || {};
    root.dataset.theme = "haruka"; root.dataset.customTheme = c.id;
    const colors = c.colors;
    const map = {background:"--bg", card:"--card", input:"--card-2", text:"--text", secondary:"--text-2", muted:"--muted", accent:"--accent", border:"--border-strong", button:"--btn-primary-bg", buttonText:"--btn-primary-fg"};
    Object.entries(map).forEach(([key, variable]) => set(variable, colors[key]));
    set("--accent-strong", colors.accent); set("--accent-dim", colors.accent + "22");
    set("--border", colors.border + "80"); set("--custom-bg", colors.background);
    set("--custom-card", colors.card); set("--custom-card-alpha", colors.card + Math.round(c.layout.cardOpacity * 255).toString(16).padStart(2,"0"));
    set("--custom-glow", colors.accent + Math.round(c.decorations.glow * 255).toString(16).padStart(2,"0"));
    set("--custom-fade", colors.background + Math.round(c.decorations.fade * 255).toString(16).padStart(2,"0"));
    if (capture) {
      set("--bg", c.capture.background); set("--card", c.capture.card);
      set("--text", colors.text); set("--muted", colors.muted); set("--active", colors.accent + "22");
      set("--capture-font", c.capture.fontSize + "px");
      document.body.dataset.themeCompact = String(c.capture.compact);
      return;
    }
    if (!original) {
      original = {};
      Object.entries(textTargets).forEach(([key, selector]) => { original[key] = document.querySelector(selector)?.innerHTML || ""; });
      original.image = document.querySelector(".haruka-oc")?.getAttribute("src") || "";
    }
    for (const key of Object.keys(textTargets)) {
      set('--custom-font-'+key, fontFamily(c.fonts?.[key], defaultFonts[key]));
    }
    Object.entries(textTargets).forEach(([key, selector]) => { const element = document.querySelector(selector); if (element) element.textContent = c.text[key] ?? ''; });
    const image = document.querySelector(".haruka-oc");
    if (image) image.src = assets[c.character.image] || "data:image/gif;base64,R0lGODlhAQABAAD/ACwAAAAAAQABAAACADs=";
    root.dataset.characterSide = c.layout.characterSide;
    set("--custom-ratio", (c.layout.characterRatio * 100) + "%");
    set("--custom-intro", c.layout.introHeight + "px");
    set("--custom-scale", c.character.scale); set("--custom-x", c.character.x + "%");
    set("--custom-y", c.character.y + "px"); set("--custom-flip", c.character.flip ? -1 : 1);
    set("--custom-character", c.character.visible ? "block" : "none");
    set("--custom-signature", c.decorations.signature ? "block" : "none");
    set("--custom-rings", c.decorations.rings ? "block" : "none");
    const bg = assets[c.background.image];
    // asset URLs are generated by backend, never arbitrary URLs/CSS from a pack.
    set("--custom-bg-image", bg && /^data:image\/(png|jpeg|webp);base64,[A-Za-z0-9+/=]+$/.test(bg) ? `url("${bg}")` : "none");
    set("--custom-dim", c.background.dim);
    set("--custom-bg-scale", c.background.scale ?? 1);
    set("--custom-bg-x", (c.background.x ?? 0) + "px");
    set("--custom-bg-y", (c.background.y ?? 0) + "px");
  }
  return {apply, reset};
})();

const themePreview = new URLSearchParams(location.search).has("preview");
if (themePreview) {
  document.documentElement.dataset.preview = "true";
  window.addEventListener("message", event => {
    if (event.source !== window.parent || event.data?.type !== "songdesk-theme-preview") return;
    const capture = location.pathname.endsWith("capture.html");
    ThemeRuntime.apply(event.data.payload, capture);
  });
  window.addEventListener("DOMContentLoaded", () => {
    window.parent.postMessage({type: "songdesk-preview-ready"}, "*");
  });
}
